"""In-process data structures for the conversational estimator.

Design notes
------------
- ``ConversationHistory.to_messages()`` returns the LLM-ready ``messages``
  array (the ``role``/``content`` dicts expected by both OpenAI and Anthropic
  through LiteLLM). The system prompt is supplied at call time because it is
  regenerated from the current ``ProjectMetadata`` each turn — it is NOT
  stored as a fixed entry in the history, which is what guarantees the
  sliding window can never drop it.
- ``ProjectMetadata`` uses ``Optional`` fields so an empty metadata block is a
  legitimate first-turn state. Merging is additive for the technology list and
  overwrite for scalar fields (see ``merge_with``).
"""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Literal
from uuid import uuid4

from pydantic import BaseModel, Field

from app.schemas.estimation import EstimationResult

Role = Literal["user", "assistant"]


class Message(BaseModel):
    """One message in the conversation history. The system prompt is NOT a
    Message — it lives outside the history because it is re-rendered each
    turn from the current ``ProjectMetadata``."""

    role: Role
    content: str
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


SUMMARY_ENVELOPE_PREFIX = (
    "[Earlier conversation summary — the recent turns below are the live thread]\n"
)


class ConversationHistory(BaseModel):
    """A sliding window of user/assistant pairs, augmented with summary + anchors.

    ``max_turns`` counts pairs (user+assistant). Three storage slots:

    - ``messages``: the recent sliding window (last ``max_turns`` pairs).
    - ``anchors``: turns flagged by ``AnchorDetector`` as durable commitments
      (signed NDA, frozen scope, compliance context, …). They live outside the
      sliding window and are never evicted by it.
    - ``summary``: a cumulative free-text summary of the older non-anchor
      turns already folded away by ``CompressionPolicy``.

    ``to_messages()`` composes the three into the array the LLM sees:

        [summary_envelope?] + anchors_in_order + recent_sliding_window
    """

    max_turns: int = Field(default=6, ge=1)
    messages: list[Message] = Field(default_factory=list)
    anchors: list[Message] = Field(default_factory=list)
    summary: str | None = Field(default=None)

    def append(self, *, user: str, assistant: str, trim: bool = True) -> None:
        """Add one turn (user message + assistant message).

        ``trim=True`` (default) drops the oldest pairs right away — the plain
        sliding window. The conversational service passes ``trim=False`` and
        then runs ``CompressionPolicy.apply``, which evicts the same pairs but
        first decides, pair by pair, whether each one is promoted to an anchor
        or folded into the cumulative summary. With ``trim=True`` the policy
        would never see an overflow, so that path must not trim here.
        """
        self.messages.append(Message(role="user", content=user))
        self.messages.append(Message(role="assistant", content=assistant))
        if trim:
            self._trim()

    def to_messages(self) -> list[dict[str, str]]:
        """Return the ``messages`` array ready to splice into the LLM call,
        excluding any system prompt (the caller prepends that fresh each turn).

        Order is intentional: the summary grounds the model in the early
        conversation, anchors carry the irreducible commitments verbatim, and
        the recent window provides the live turn-by-turn context.
        """
        out: list[dict[str, str]] = []
        if self.summary:
            # A synthetic user message: routes cleanly on both providers, and
            # the bracketed header tells the model it is context, not a request.
            out.append({"role": "user", "content": SUMMARY_ENVELOPE_PREFIX + self.summary})
        out.extend({"role": a.role, "content": a.content} for a in self.anchors)
        out.extend({"role": m.role, "content": m.content} for m in self.messages)
        return out

    def to_messages_list(
        self, *, system_prompt: str, user_message: str | None = None
    ) -> list[dict[str, str]]:
        """Return the full ``messages`` array for the LLM API:

            [system] + [summary?] + anchors + sliding window (oldest → newest)
            + [current user]?

        ``system_prompt`` must be regenerated by the caller from the CURRENT
        ``ProjectMetadata`` every turn (``render_conversational_prompt``); it
        is passed in rather than stored so it is always fresh and, being
        outside ``messages``, the window can never evict it — the system prompt
        is an invariant on top of the window. ``user_message`` is the turn
        being asked now (not yet in the history; ``append`` adds it once the
        assistant has answered).

        estimator_sesion5 builds this same array inline in the service from
        ``to_messages()``; this method is that assembly, named.
        """
        out: list[dict[str, str]] = [{"role": "system", "content": system_prompt}]
        out.extend(self.to_messages())
        if user_message is not None:
            out.append({"role": "user", "content": user_message})
        return out

    def _trim(self) -> None:
        max_messages = self.max_turns * 2
        overflow = len(self.messages) - max_messages
        if overflow > 0:
            # Drop in pairs so role alternation stays intact.
            if overflow % 2 != 0:
                overflow += 1
            del self.messages[:overflow]


class ProjectMetadata(BaseModel):
    """Facts about the project under discussion, kept across turns.

    All fields are optional: on the first turn the LLM has not yet committed
    to a project name, team size, technology list or scope. They are
    populated turn by turn.
    """

    project_name: str | None = Field(default=None, max_length=120)
    assumed_team_size: int | None = Field(default=None, ge=1, le=50)
    mentioned_technologies: list[str] = Field(default_factory=list)
    agreed_scope: str | None = Field(default=None, max_length=2000)

    def is_empty(self) -> bool:
        return (
            self.project_name is None
            and self.assumed_team_size is None
            and not self.mentioned_technologies
            and self.agreed_scope is None
        )

    def merge_with(self, update: "ProjectMetadata") -> "ProjectMetadata":
        """Return a new metadata where non-null fields from ``update`` win,
        and ``mentioned_technologies`` is the case-insensitive union.

        Scalar overwrite + list union is the right default here: later turns
        are allowed to refine the project name or team size as the conversation
        clarifies them, but technologies accumulate (the user adding a new
        stack item shouldn't make the previous ones disappear).
        """
        merged_tech = list(self.mentioned_technologies)
        seen = {t.lower() for t in merged_tech}
        for tech in update.mentioned_technologies:
            if tech.lower() not in seen:
                merged_tech.append(tech)
                seen.add(tech.lower())

        return ProjectMetadata(
            project_name=update.project_name or self.project_name,
            assumed_team_size=update.assumed_team_size or self.assumed_team_size,
            mentioned_technologies=merged_tech,
            agreed_scope=update.agreed_scope or self.agreed_scope,
        )


class Session(BaseModel):
    """A conversational estimation session.

    Lives in memory of the FastAPI process. State is lost on restart, which is
    intentional for the exercise — persistence enters with the live session's
    advanced topics.

    ``last_estimate`` (estimador addition, not in estimator_sesion5) is the
    latest validated estimation. It is rendered into the system prompt as
    ``<current_estimate>`` so each turn re-estimates the WHOLE project on top
    of it: without it, gpt-4o-mini answered "add billing" by estimating only
    the billing module, and the total went DOWN as scope was added. Unlike the
    history it is never evicted by the sliding window.

    ``last_resolved_tier`` and ``last_tier_rule`` cache the latest tier
    resolution so ``GET /sessions/{id}`` can show it ("executive
    (nda_detected)") without re-running the resolver.
    """

    session_id: str = Field(default_factory=lambda: str(uuid4()))
    history: ConversationHistory = Field(default_factory=ConversationHistory)
    metadata: ProjectMetadata = Field(default_factory=ProjectMetadata)
    last_estimate: EstimationResult | None = None
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    last_resolved_tier: str | None = None
    last_tier_rule: str | None = None
    # Turns committed so far (actor or ACB). Monotonic, unlike the window
    # size, which plateaus at ``max_turns`` once compression starts evicting.
    turn_count: int = Field(default=0, ge=0)
